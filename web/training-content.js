  function normalize(text) {
    return String(text || '').replace(/\s+/g, '').toLowerCase();
  }

  function evaluateSummary(article, transcript) {
    const value = normalize(transcript);
    const matched = article.keywords.filter((keyword) => value.includes(normalize(keyword)));
    const missing = article.keywords.filter((keyword) => !matched.includes(keyword));
    const pointHits = article.points.filter((point) => {
      const tokens = point.replace(/[，。、“”]/g, '').match(/[\u3400-\u9fff]{2,4}/g) || [];
      return tokens.some((token) => value.includes(token));
    });
    const keywordScore = Math.round(matched.length / article.keywords.length * 100);
    const pointScore = Math.round(pointHits.length / article.points.length * 100);
    return {
      matched,
      missing,
      pointHits,
      keywordScore,
      pointScore,
      score: Math.round(keywordScore * 0.65 + pointScore * 0.35)
    };
  }

